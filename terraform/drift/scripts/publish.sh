#!/usr/bin/env bash
# Commit the staged drift fix to BRANCH, force-push it, and open or update one PR:
# ready when SOLVED=true, draft otherwise. The manual-steps comment is kept sticky.
#
# Env: GH_TOKEN, GH_REPO, NAME, BRANCH, BASE, SOLVED, PR_DIR (body.md, comment.md).
set -euo pipefail

marker='<!-- terraform-drift -->'
title="chore: sync $NAME Terraform with live AWS state"

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git checkout -B "$BRANCH"
# An empty commit still lets a draft PR carry the manual steps when nothing could be fixed.
git commit --allow-empty -m "$title" -m "Generated by the terraform/drift action."
git push --force origin "HEAD:refs/heads/$BRANCH"

pr=$(gh pr list --head "$BRANCH" --base "$BASE" --state open --json number --jq '.[0].number // empty')
if [ -z "$pr" ]; then
  draft=()
  [ "$SOLVED" = "true" ] || draft=(--draft)
  gh pr create --head "$BRANCH" --base "$BASE" --title "$title" --body-file "$PR_DIR/body.md" "${draft[@]}"
  pr=$(gh pr list --head "$BRANCH" --base "$BASE" --state open --json number --jq '.[0].number')
else
  gh pr edit "$pr" --title "$title" --body-file "$PR_DIR/body.md"
  if [ "$SOLVED" = "true" ]; then gh pr ready "$pr" || true; else gh pr ready "$pr" --undo || true; fi
fi

existing=$(gh api --paginate "repos/$GH_REPO/issues/$pr/comments" \
  --jq ".[] | select(.body | startswith(\"$marker\")) | .id" | tail -n1)
if [ -n "$existing" ]; then
  gh api --method PATCH "repos/$GH_REPO/issues/comments/$existing" -F body=@"$PR_DIR/comment.md" >/dev/null
elif [ "$SOLVED" != "true" ]; then
  gh pr comment "$pr" --body-file "$PR_DIR/comment.md"
fi

url=$(gh pr view "$pr" --json url --jq .url)
echo "pr-url=$url" >> "$GITHUB_OUTPUT"
echo "Drift PR: $url" >> "$GITHUB_STEP_SUMMARY"
